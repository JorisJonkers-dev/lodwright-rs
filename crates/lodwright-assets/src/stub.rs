//! The stub plugin that registers a packed archive: the smallest plugin the game accepts, named like the archive.
//!
//! A packed archive is found because a plugin of the same name is in the load order (rows
//! `fnv-archive-loading`, `bsa-archive-registration`); the plugin holds no record and changes nothing in the game.
//! Layout: the TES4 header record (`plugin-record-header`) with a HEDR subrecord (`plugin-subrecord-layout`),
//! the values measured as numbers on the game's own plugin headers (`plugin-stub-header-values`), an author and a
//! description so a tool can tell what the plugin is for, and one master: the game opens the archives of a plugin
//! only when its master list is not empty.
//!
//! Whether the game then loads the archive on the target engine is measured, not assumed (issue 132).

use std::fmt;

// source: plugin-record-header
const SIGNATURE: &[u8; 4] = b"TES4";
// source: plugin-stub-header-values
const HEDR_VERSION: f32 = 1.34;
// source: plugin-stub-header-values
const NEXT_OBJECT_ID: u32 = 0x800;
// source: plugin-stub-header-values
const FORM_VERSION: u32 = 0xF;

/// The author written into the stub, so that a tool can recognise a generated stub.
pub const AUTHOR: &str = "lodwright";
/// The description written into the stub.
pub const DESCRIPTION: &str =
    "Registers the packed LOD archive of the same name. Generated by lodwright; holds no record.";

/// Why a name was refused.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BadName(pub String);

impl fmt::Display for BadName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{:?} cannot be the name of an archive and its plugin",
            self.0
        )
    }
}

impl std::error::Error for BadName {}

/// The file names of a packed archive and its stub: `<base>.bsa` and `<base>.esp`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PackedNames {
    /// The archive's file name.
    pub archive: String,
    /// The stub plugin's file name: the archive's base name with `.esp`.
    pub plugin: String,
}

impl PackedNames {
    /// Names for the base name `base` (no extension, no folder).
    ///
    /// # Errors
    /// [`BadName`] for an empty name, one with a separator, a control character or a character no file system
    /// takes, one that is not ASCII, one that ends in a dot or space, or one that already ends in `.esp`, `.esm`
    /// or `.bsa`.
    pub fn new(base: &str) -> Result<Self, BadName> {
        let lower = base.to_ascii_lowercase();
        let bad = base.is_empty()
            || !base.is_ascii()
            || base.ends_with(['.', ' '])
            || base
                .chars()
                .any(|c| c.is_control() || "<>:\"/\\|?*".contains(c))
            || [".esp", ".esm", ".bsa"].iter().any(|e| lower.ends_with(e));
        if bad {
            return Err(BadName(base.to_owned()));
        }
        Ok(Self {
            archive: format!("{base}.bsa"),
            plugin: format!("{base}.esp"),
        })
    }
}

fn subrecord(out: &mut Vec<u8>, signature: [u8; 4], data: &[u8]) {
    out.extend_from_slice(&signature);
    out.extend_from_slice(&u16::try_from(data.len()).unwrap_or(u16::MAX).to_le_bytes());
    out.extend_from_slice(data);
}

fn zstring(text: &str) -> Vec<u8> {
    let mut bytes = text.as_bytes().to_vec();
    bytes.push(0);
    bytes
}

/// The bytes of the stub plugin: a TES4 record, not a master, one master (`master`, whose file is `master_size`
/// bytes), a record count of 0.
///
/// The master is not optional: the game opens the archives of a plugin only when its master list is not empty
/// (measured in the engine, issue 132; `plugin-stub-header-values`). Pass the first plugin of the load order,
/// normally `FalloutNV.esm`, and its size in bytes (the game warns when a master's size differs from the one
/// stored).
///
/// Deterministic: the same bytes for the same arguments, on every system.
#[must_use]
pub fn stub_plugin(master: &str, master_size: u64) -> Vec<u8> {
    // source: plugin-subrecord-layout
    let mut data = Vec::new();
    let mut hedr = Vec::with_capacity(12);
    hedr.extend_from_slice(&HEDR_VERSION.to_le_bytes());
    hedr.extend_from_slice(&0_u32.to_le_bytes());
    hedr.extend_from_slice(&NEXT_OBJECT_ID.to_le_bytes());
    subrecord(&mut data, *b"HEDR", &hedr);
    subrecord(&mut data, *b"CNAM", &zstring(AUTHOR));
    subrecord(&mut data, *b"SNAM", &zstring(DESCRIPTION));
    subrecord(&mut data, *b"MAST", &zstring(master));
    subrecord(&mut data, *b"DATA", &master_size.to_le_bytes());
    // source: plugin-record-header
    let mut out = Vec::with_capacity(24 + data.len());
    out.extend_from_slice(SIGNATURE);
    out.extend_from_slice(&u32::try_from(data.len()).unwrap_or(u32::MAX).to_le_bytes());
    out.extend_from_slice(&0_u32.to_le_bytes());
    out.extend_from_slice(&0_u32.to_le_bytes());
    out.extend_from_slice(&0_u32.to_le_bytes());
    out.extend_from_slice(&FORM_VERSION.to_le_bytes());
    out.extend_from_slice(&data);
    out
}

#[cfg(test)]
mod tests {
    use super::{AUTHOR, PackedNames, stub_plugin};

    #[test]
    fn the_stub_is_the_same_bytes_every_time() {
        assert_eq!(
            stub_plugin("FalloutNV.esm", 7),
            stub_plugin("FalloutNV.esm", 7)
        );
        assert_ne!(
            stub_plugin("FalloutNV.esm", 7),
            stub_plugin("FalloutNV.esm", 8)
        );
    }

    #[test]
    fn the_header_size_counts_exactly_the_subrecords() {
        let bytes = stub_plugin("FalloutNV.esm", 7);
        let size = u32::from_le_bytes(bytes[4..8].try_into().unwrap()) as usize;
        assert_eq!(bytes.len(), 24 + size);
        assert_eq!(&bytes[..4], b"TES4");
        // flags: not a master
        assert_eq!(u32::from_le_bytes(bytes[8..12].try_into().unwrap()), 0);
    }

    #[test]
    fn the_names_share_the_base_and_differ_in_the_extension() {
        let names = PackedNames::new("Lodwright LOD").unwrap();
        assert_eq!(names.archive, "Lodwright LOD.bsa");
        assert_eq!(names.plugin, "Lodwright LOD.esp");
    }

    #[test]
    fn names_that_cannot_be_files_are_refused() {
        for bad in [
            "",
            "a/b",
            "a\\b",
            "a:b",
            "x.",
            "x ",
            "caf\u{e9}",
            "x.ESP",
            "x.bsa",
            "a\u{7}b",
            "a*b",
        ] {
            assert!(PackedNames::new(bad).is_err(), "{bad:?}");
        }
        assert!(PackedNames::new("a.b").is_ok());
        assert!(super::BadName("x".into()).to_string().contains("\"x\""));
    }

    #[test]
    fn the_author_marks_the_stub() {
        let bytes = stub_plugin("FalloutNV.esm", 7);
        let needle = format!("{AUTHOR}\0");
        assert!(bytes.windows(needle.len()).any(|w| w == needle.as_bytes()));
    }
}
